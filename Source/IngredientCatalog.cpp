std::vector<Food> IngredientCatalog::matching(const juce::String& query, const juce::String& category) {
    std::vector<Food> result;
    for (const auto& food : all()) {
        const bool categoryMatch = category.isEmpty() || category == "All foods" || juce::String(food.category) == category;
        const bool queryMatch = query.isEmpty() || juce::String(food.name).containsIgnoreCase(query);
        if (categoryMatch && queryMatch) result.push_back(food);
    }
    return result;
}

Food IngredientCatalog::custom(const juce::String& name) {
    return {name.toStdString(), "Custom", "✦", -1.0};
}

